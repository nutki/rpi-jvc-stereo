SH1122* oled;
FrameBuffer* fb;
void display_init() {
    framebuffer_init();
    printf("Initializing SH1122 OLED display...\n");
    oled = sh1122_create("/dev/spidev0.0", 256, 48, 2);
    if (!oled) {
        fprintf(stderr, "Failed to initialize display\n");
        exit(1);
    }
    fb = oled->fb;
    
    printf("SH1122 OLED display driver loaded\n");
}
void display_close() {
    if (oled) {
        sh1122_destroy(oled);
        oled = NULL;
    }
}
void display_show() {
    if (oled) sh1122_show(oled);
}
